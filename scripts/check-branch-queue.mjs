import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
const calls = [];
const apiClient = { get: path => new Promise((resolve, reject) => calls.push({ path, resolve, reject })) };
const source = fs.readFileSync('src/api/branchQueueApi.js', 'utf8').replace(/^import .*;\r?\n/gm, '').replace(/export /g, '');
const context = vm.createContext({ apiClient, URLSearchParams });
vm.runInContext(source + '\nglobalThis.api = branchQueueApi;', context);
const api = context.api;
const first = api.list();
const duplicate = api.list({ page: 1, limit: 10 });
assert.equal(first, duplicate);
assert.equal(calls.length, 1);
const otherPage = api.list({ page: 2 });
assert.equal(calls.length, 2);
assert.equal(calls[1].path, '/api/v1/branch/queue?page=2&limit=10');
calls[0].resolve({ success: true, data: { items: [], pagination: { total: 0 } } });
calls[1].resolve({ success: true });
await Promise.all([first, duplicate, otherPage]);
const fresh = api.list();
assert.equal(calls.length, 3);
calls[2].reject(new Error('Network failure'));
await assert.rejects(fresh, /Network failure/);
const retry = api.list();
assert.equal(calls.length, 4);
calls[3].resolve({ success: false, message: 'Queue unavailable' });
await assert.rejects(retry, /Queue unavailable/);
const final = api.list();
assert.equal(calls.length, 5);
calls[4].resolve({ success: true });
await final;
console.log('Queue duplicate requests share one call; pagination, fresh loads, and retries verified.');
