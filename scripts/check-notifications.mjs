import assert from 'node:assert/strict';
import { audienceLabel, emptyAnnouncement, restaurantAnnouncement, notificationStore, validateAnnouncement } from '../src/services/notificationService.js';
const announcement = { ...emptyAnnouncement(), title: 'Maintenance', message: 'Please plan ahead.' };
const restaurant = { id: '1', kind: 'restaurants', name: 'Spice Hub' };
assert.equal(validateAnnouncement(announcement, 'sent'), '');
assert.equal(audienceLabel(announcement), 'All restaurants');
assert.match(validateAnnouncement(emptyAnnouncement(), 'draft'), /title/);
assert.equal(validateAnnouncement({ ...announcement, message: '' }, 'draft'), '');
assert.match(validateAnnouncement({ ...announcement, message: ' ' }, 'sent'), /message/);
assert.match(validateAnnouncement({ ...announcement, audience: 'restaurant' }, 'sent'), /at least one restaurant/);
assert.equal(validateAnnouncement({ ...announcement, audience: 'restaurant', recipients: [restaurant] }, 'sent'), '');
assert.equal(audienceLabel({ ...announcement, audience: 'restaurant', recipients: [restaurant] }), 'Spice Hub');
assert.equal(validateAnnouncement({ ...announcement, audience: 'restaurant', recipients: [restaurant, { ...restaurant, id: '2' }] }, 'sent'), '');
for (const audience of ['all', 'groups', 'selected', 'customers', 'managers']) {
  assert.match(validateAnnouncement({ ...announcement, audience }, 'sent'), /only.*restaurants/);
}
assert.match(validateAnnouncement({ ...announcement, audience: 'restaurant', recipients: [{ id: '2', kind: 'customers' }] }, 'sent'), /only.*restaurants/);
assert.match(validateAnnouncement(announcement, 'scheduled'), /immediate/);
assert.match(validateAnnouncement({ ...announcement, title: 'x'.repeat(121) }, 'sent'), /120/);
assert.match(validateAnnouncement({ ...announcement, message: 'x'.repeat(2001) }, 'draft'), /2,000/);
assert.match(validateAnnouncement({ ...announcement, priority: 'invalid' }, 'sent'), /priority/);
const values = new Map();
globalThis.localStorage = { getItem: key => values.get(key) ?? null, setItem: (key, value) => values.set(key, value) };
const first = notificationStore('admin-a');
assert.deepEqual(first.list(), []);
const records = [{ ...announcement, id: 'one', status: 'draft' }, { ...announcement, id: 'two', status: 'sent' }];
first.save(records);
assert.deepEqual(first.list(), records);
assert.deepEqual(notificationStore('admin-b').list(), []);
const legacy = { ...announcement, id: 'legacy', audience: 'all', groups: [], status: 'scheduled', timing: 'later', scheduledAt: '2030-01-01', searchText: 'Everyone', recipients: [] };
first.save([legacy]);
const migrated = first.list()[0];
assert.equal(migrated.status, 'draft');
assert.equal(migrated.audience, 'restaurant');
assert.equal('scheduledAt' in migrated, false);
assert.equal('timing' in migrated, false);
assert.match(validateAnnouncement(migrated, 'sent'), /at least one restaurant/);
first.save([{ ...legacy, status: 'sent' }]);
assert.equal(first.list()[0].audience, 'all');
assert.equal(audienceLabel(first.list()[0]), 'Previous audience: everyone');
const converted = restaurantAnnouncement({ ...legacy, audience: 'selected', recipients: [restaurant, { id: '2', kind: 'customers' }] });
assert.deepEqual(converted.recipients, [restaurant]);
values.set('broken', '{');
assert.throws(() => notificationStore('broken').list());
values.set('broken', '{}');
assert.throws(() => notificationStore('broken').list(), /could not be read/);
globalThis.localStorage.setItem = () => { throw new Error('Storage unavailable'); };
assert.throws(() => first.save(records), /Storage unavailable/);
console.log('Restaurant-only targeting, immediate sending, legacy draft migration, and persistence checks passed.');

const multiple = { ...announcement, audience: 'restaurant', recipients: [restaurant, { id: '2', kind: 'restaurants', name: 'Cafe Two' }] };
assert.equal(audienceLabel(multiple), 'Spice Hub, Cafe Two');
assert.deepEqual(restaurantAnnouncement(multiple).recipients, multiple.recipients);