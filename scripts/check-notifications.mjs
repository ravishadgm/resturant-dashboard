import assert from 'node:assert/strict';
import fs from 'node:fs';
import { emptyAnnouncement, audienceLabel, validateAnnouncement, notificationStore } from '../src/services/notificationService.js';
const valid = { ...emptyAnnouncement(), title: 'Update', message: 'Opening hours changed.' };
assert.equal(validateAnnouncement(valid, 'sent'), '');
assert.equal(audienceLabel(valid), 'All branches');
assert.match(validateAnnouncement({ ...valid, audience: 'branch' }, 'sent'), /at least one/);
const selected = { ...valid, audience: 'branch', recipients: [{ id: '1', kind: 'branches', name: 'City Branch' }, { id: '2', kind: 'branches', name: 'West Branch' }] };
assert.equal(validateAnnouncement(selected, 'sent'), '');
assert.equal(audienceLabel(selected), 'City Branch, West Branch');
assert.match(validateAnnouncement({ ...selected, recipients: [{ id: '3', kind: 'customers' }] }, 'sent'), /Only branches/);
assert.match(validateAnnouncement({ ...valid, priority: 'invalid' }, 'sent'), /priority/);
assert.match(validateAnnouncement({ ...valid, message: ' ' }, 'sent'), /message/);
assert.match(validateAnnouncement(valid, 'scheduled'), /immediate/);
const values = new Map();
globalThis.localStorage = { getItem: key => values.get(key) ?? null, setItem: (key, value) => values.set(key, value) };
const record = { ...selected, id: 'one', status: 'sent' };
notificationStore('restaurant-a').save([record]);
assert.deepEqual(notificationStore('restaurant-a').list(), [record]);
assert.deepEqual(notificationStore('restaurant-b').list(), []);
values.set('broken', '{}');
assert.throws(() => notificationStore('broken').list());
const ui = fs.readFileSync('src/modules/notifications/Notifications.jsx', 'utf8');
assert.ok(ui.includes("branchApi.list({ page, limit: 10, search, scope: 'restaurant' })"));
assert.ok(!ui.includes('restaurantApi.list'));
console.log('Restaurant notifications: branch targeting, priority, account isolation, and scoped recipient API checks passed.');
