import assert from 'node:assert/strict';
import fs from 'node:fs';
import {branchProfileForm,branchProfilePayload} from '../src/utils/branchProfile.js';
const form=branchProfileForm({name:'Admin Branch',address:null,city:'Surat',latitude:'21.21000000',longitude:'72.78000000',slot_interval_minutes:30,slot_capacity:20,notify_lead_minutes:15,queue_enabled:true,rating:'4.5',map_url:'https://maps.google.com/maps?test=1'});
let payload=branchProfilePayload(form);
assert.equal(payload.latitude,21.21);
assert.equal(payload.longitude,72.78);
assert.equal(payload.rating,4.5);
assert.equal(payload.queue_enabled,true);
assert.equal(payload.address,'');
assert.equal('advance_booking_days' in payload,false);
payload=branchProfilePayload({...form,advance_booking_days:'0',notify_lead_minutes:'0',queue_enabled:false});
assert.equal(payload.advance_booking_days,0);
assert.equal(payload.notify_lead_minutes,0);
assert.equal(payload.queue_enabled,false);
assert.throws(()=>branchProfilePayload({...form,slot_capacity:'1.5'}),/valid/);
assert.throws(()=>branchProfilePayload({...form,latitude:'91'}),/valid/);
assert.throws(()=>branchProfilePayload({...form,map_url:'javascript:alert(1)'}),/HTTP/);
assert.throws(()=>branchProfilePayload({...form,name:' '}),/required/);
