import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
const calls = [];
let response = { success: true, data: { items: [{ table_id: 1, table_number: 'T1', capacity: 4, status: 'AVAILABLE', city: 'Surat', branch_name: 'Admin Branch', restaurant_name: 'Spice Hub' }], pagination: { total: 1 } } };
const apiClient = Object.fromEntries(['get','post','patch'].map(method => [method, async (path, body) => { calls.push({method,path,body}); return response; }]));
const source = fs.readFileSync('src/api/branchTableApi.js','utf8').replace(/^import .*;\r?\n/gm,'').replace(/export /g,'');
const context = vm.createContext({apiClient,URLSearchParams});
vm.runInContext(source+'\nglobalThis.api = branchTableApi;',context);
const api = context.api;
const listed = await api.list({page:2,limit:20,search:'T1'});
const url = new URL(calls[0].path,'https://example.com');
assert.equal(url.pathname,'/api/v1/branch/tables');
assert.equal(url.searchParams.get('page'),'2');
assert.equal(url.searchParams.get('limit'),'20');
assert.equal(url.searchParams.get('search'),'T1');
assert.equal(url.searchParams.has('branch_id'),false);
assert.equal(listed.data.items[0].restaurant_name,'Spice Hub');
await api.create({table_number:' T3 ',capacity:'4',status:'AVAILABLE',branch_id:99});
assert.equal(calls[1].method,'post');
assert.equal(calls[1].path,'/api/v1/branch/tables');
assert.deepEqual(JSON.parse(JSON.stringify(calls[1].body)),{table_number:'T3',capacity:4,status:'AVAILABLE'});
await api.updateStatus(1,'OCCUPIED');
assert.equal(calls[2].method,'patch');
assert.equal(calls[2].path,'/api/v1/branch/tables/1/status');
assert.deepEqual(JSON.parse(JSON.stringify(calls[2].body)),{status:'OCCUPIED'});
response={success:false,message:'Update rejected'};
await assert.rejects(api.updateStatus(1,'AVAILABLE'),/Update rejected/);
const ui=fs.readFileSync('src/modules/tables/TableList.jsx','utf8');
const fields=ui.match(/const displayFields = \[[\s\S]*?\];/)[0];
assert.equal(/table_id|branch_id|restaurant_id|created_at|updated_at/.test(fields),false);
assert.ok(fs.readFileSync('src/routes/AppRoutes.jsx','utf8').includes('path="/tables" element={<TableList/>}'));
console.log('Branch table listing, creation payload, status PATCH, error handling, and route checks passed.');
