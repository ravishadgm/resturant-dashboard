import assert from 'node:assert/strict';
import fs from 'node:fs';
import { WEEKDAYS, normalizeSchedule, schedulePayload } from '../src/utils/branchSchedule.js';
const days = normalizeSchedule(WEEKDAYS.map(day => ({day_of_week:day,open_time:'09:00',close_time:'21:00',is_closed:day === 'SUNDAY',is_set:true})));
const body = schedulePayload(days);
assert.equal(body.schedules.length,7);
assert.deepEqual(body.schedules[0],{day_of_week:'MONDAY',open_time:'09:00',close_time:'21:00',is_closed:false});
assert.deepEqual(body.schedules[6],{day_of_week:'SUNDAY',is_closed:true});
assert.equal(normalizeSchedule([{day_of_week:'MONDAY',open_time:'09:00:00',close_time:'21:00:00',is_closed:false}])[0].open_time,'09:00');
assert(normalizeSchedule([]).every(day=>!day.is_set && day.is_closed));
assert.throws(()=>schedulePayload([{...days[0],open_time:'25:00'},...days.slice(1)]),/opening and closing/);
assert.throws(()=>schedulePayload([{...days[0],close_time:'09:00'},...days.slice(1)]),/must differ/);
assert.throws(()=>schedulePayload(days.slice(1)),/Please set timings/);
let gets=0;
let sent;
let resolveGet;
globalThis.scheduleTestClient={get:path=>{gets++;return new Promise(resolve=>{resolveGet=()=>resolve({path});});},post:async(path,body)=>{sent={path,body};return {success:true};}};
let source = fs.readFileSync('src/api/branchScheduleApi.js','utf8').replace(/^import .*;\r?\n/gm,'');
source = 'const apiClient=globalThis.scheduleTestClient;\nconst schedulePayload='+schedulePayload.toString()+';\nconst WEEKDAYS='+JSON.stringify(WEEKDAYS)+';\n'+source;
const {branchScheduleApi} = await import('data:text/javascript;base64,'+Buffer.from(source).toString('base64'));
const first=branchScheduleApi.get(1);
assert.equal(branchScheduleApi.get(1),first);
assert.equal(gets,1);
resolveGet();
assert.equal((await first).path,'/api/v1/restaurant/branches/1/schedules');
await branchScheduleApi.save(1,days);
assert.equal(sent.path,'/api/v1/restaurant/branches/1/schedules');
assert.deepEqual(sent.body,body);
console.log('Schedule checks passed: seven-day order, time validation, closed-day payload, GET deduplication, and POST endpoint.');
